# -*- coding: utf-8 -*-
"""Build the defense speech + Q&A document (.docx).

Run from repo root:  python3 thesis/build_defense.py
Output: thesis/Захист_доповідь_та_питання.docx
"""
from __future__ import annotations

import os

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "thesis", "Захист_доповідь_та_питання.docx")
FONT = "Times New Roman"

d = Document()
st = d.styles["Normal"]
st.font.name = FONT; st.font.size = Pt(14)
st.element.rPr.rFonts.set(qn("w:cs"), FONT)
st.paragraph_format.line_spacing = 1.3
st.paragraph_format.space_after = Pt(6)


def h(text, size=16):
    p = d.add_paragraph()
    r = p.add_run(text); r.font.name = FONT; r.font.size = Pt(size); r.font.bold = True
    r.font.color.rgb = RGBColor(0x19, 0x40, 0x7A)
    p.paragraph_format.space_before = Pt(10)
    return p


def para(text, bold=False, indent=False):
    p = d.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    if indent:
        p.paragraph_format.first_line_indent = Cm(1.0)
    r = p.add_run(text); r.font.name = FONT; r.font.size = Pt(14); r.font.bold = bold
    return p


def slide(label, text):
    p = d.add_paragraph()
    p.paragraph_format.space_before = Pt(8)
    r = p.add_run(label + "  "); r.font.name = FONT; r.font.size = Pt(13)
    r.font.bold = True; r.font.color.rgb = RGBColor(0xB0, 0x30, 0x30)
    r2 = p.add_run(text); r2.font.name = FONT; r2.font.size = Pt(14)
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY


def qa(q, a):
    p = d.add_paragraph(); p.paragraph_format.space_before = Pt(8)
    r = p.add_run("Питання. "); r.font.name = FONT; r.font.size = Pt(14); r.font.bold = True
    r2 = p.add_run(q); r2.font.name = FONT; r2.font.size = Pt(14); r2.font.bold = True
    p2 = d.add_paragraph(); p2.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    r3 = p2.add_run("Відповідь. "); r3.font.name = FONT; r3.font.size = Pt(14); r3.font.italic = True
    r4 = p2.add_run(a); r4.font.name = FONT; r4.font.size = Pt(14)


# ---------------------------------------------------------------- title
t = d.add_paragraph(); t.alignment = WD_ALIGN_PARAGRAPH.CENTER
r = t.add_run("Текст доповіді на захист і можливі запитання")
r.font.name = FONT; r.font.size = Pt(16); r.font.bold = True
t2 = d.add_paragraph(); t2.alignment = WD_ALIGN_PARAGRAPH.CENTER
r = t2.add_run("Кваліфікаційна робота бакалавра. Макаренко В. А., група ТК-41")
r.font.name = FONT; r.font.size = Pt(13); r.font.italic = True
para("Орієнтовна тривалість доповіді — до 10 хвилин (приблизно 1100 слів). "
     "Позначки [Слайд N] вказують момент перемикання слайдів.", italic := False)

