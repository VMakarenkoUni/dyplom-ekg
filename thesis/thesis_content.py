def content_toc(b):
    b.h1("Зміст")
    p = b.doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.first_line_indent = Cm(0)
    run = p.add_run()
    fb = OxmlElement("w:fldChar"); fb.set(qn("w:fldCharType"), "begin")
    it = OxmlElement("w:instrText"); it.set(qn("xml:space"), "preserve")
    it.text = 'TOC \\o "1-3" \\h \\z \\u'
    fs = OxmlElement("w:fldChar"); fs.set(qn("w:fldCharType"), "separate")
    t = OxmlElement("w:t"); t.text = ("Зміст формується автоматично. Щоб його "
                                      "оновити, виділіть документ (Ctrl+A) і "
                                      "натисніть F9.")
    fe = OxmlElement("w:fldChar"); fe.set(qn("w:fldCharType"), "end")
    run._r.append(fb); run._r.append(it); run._r.append(fs); run._r.append(t); run._r.append(fe)
    for r in p.runs:
        r.font.name = FONT; r.font.size = Pt(SIZE)


